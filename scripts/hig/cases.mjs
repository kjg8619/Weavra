export function chooseAlias(counts) {
  const total = counts.reduce((sum, count) => sum + count, 0);
  if (total !== 1) throw new Error(`Selector ambiguity/missing target: ${counts.join(",")}`);
  return counts.findIndex((count) => count === 1);
}

