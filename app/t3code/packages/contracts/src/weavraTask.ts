import * as Option from "effect/Option";
import * as Schema from "effect/Schema";
import { CommandId, IsoDateTime } from "./baseSchemas.ts";

// Intentionally mirrored by Runtime contracts.ts. These are data contracts, not capabilities.
export const WEAVRA_ANALYSIS_CONTEXT_MAX_BYTES = 8192;
const utf8 = new TextEncoder();
// Bound identities must round-trip byte-for-byte with Runtime, unlike free-form UI IDs.
const exactIdentity = Schema.String.check(Schema.isPattern(/\S/));
const EnvironmentId = exactIdentity.pipe(Schema.brand("EnvironmentId"));
const ProjectId = exactIdentity.pipe(Schema.brand("ProjectId"));
const ThreadId = exactIdentity.pipe(Schema.brand("ThreadId"));
const counter = Schema.Int.check(
  Schema.isBetween({ minimum: 0, maximum: Number.MAX_SAFE_INTEGER }),
);
const positive = counter.check(Schema.isGreaterThanOrEqualTo(1));
const uuid = Schema.String.check(
  Schema.isPattern(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/),
);
const digest = Schema.String.check(Schema.isPattern(/^sha256:[0-9a-f]{64}$/));
const identifier = Schema.String.check(
  Schema.isMinLength(1),
  Schema.isMaxLength(128),
  Schema.isPattern(/^[A-Za-z0-9._:-]+$/),
);
const text = (max: number) =>
  Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(max), Schema.isPattern(/\S/));

// Effect's default Struct decoder strips excess keys. Reject them before decoding at these
// authority boundaries, including nested objects and JSON read back from persistence.
function closed<S extends Schema.ConstraintDecoder<unknown>>(schema: S) {
  const decode = Schema.decodeUnknownOption(schema, { onExcessProperty: "error" });
  return Schema.Unknown.check(Schema.makeFilter((value) => Option.isSome(decode(value)))).pipe(
    Schema.decodeTo(schema),
  );
}

export const WeavraTaskId = uuid.pipe(Schema.brand("WeavraTaskId"));
export type WeavraTaskId = typeof WeavraTaskId.Type;
/** Runtime Task Contract UUID, never generated by the App. */
export const WeavraExecutionId = uuid.pipe(Schema.brand("WeavraExecutionId"));
export type WeavraExecutionId = typeof WeavraExecutionId.Type;

const relativePath = text(256).check(
  Schema.makeFilter(
    (value) =>
      !/^[A-Za-z]:/.test(value) &&
      !value.includes("\\") &&
      Array.from(value).every(
        (character) => character.charCodeAt(0) > 31 && character !== "\u007f",
      ) &&
      value.split("/").every((segment) => segment !== "" && segment !== "." && segment !== ".."),
  ),
);
const absolutePath = text(4096).check(
  Schema.makeFilter(
    (value) =>
      /^(\/|[A-Za-z]:[\\/]|\\\\)/.test(value) &&
      Array.from(value).every((character) => character.charCodeAt(0) > 31),
  ),
);
export const WeavraCheckoutIdentity = Schema.Struct({
  canonicalCwd: absolutePath,
  repositoryRoot: absolutePath,
  headCommit: Schema.String.check(Schema.isPattern(/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/)),
  workspaceDigest: digest,
}).pipe(closed);
export type WeavraCheckoutIdentity = typeof WeavraCheckoutIdentity.Type;

const sourceReference = Schema.Struct({
  path: relativePath,
  digest,
  lines: Schema.optionalKey(
    Schema.Struct({ start: positive, end: positive }).check(
      Schema.makeFilter((lines) => lines.end >= lines.start),
    ),
  ),
});
export const WeavraTaskFinding = Schema.Struct({
  text: text(500),
  provenance: Schema.Literals(["MODEL", "USER", "HOST_OBSERVATION"]),
  reference: Schema.Union([
    Schema.Struct({ kind: Schema.Literal("source"), path: relativePath }),
    Schema.Struct({
      kind: Schema.Literal("message"),
      // Preserve the reviewed packet's identity and byte count exactly, as Runtime does.
      threadId: ThreadId,
      messageId: Schema.String.check(Schema.isPattern(/\S/)).pipe(Schema.brand("MessageId")),
    }),
  ]),
});
export const WeavraAnalysisContext = Schema.Struct({
  version: Schema.Literal(1),
  packetVersion: positive,
  authority: Schema.Literal("ADVISORY_ONLY"),
  reviewedAt: counter,
  symptom: text(1000),
  observations: Schema.Array(WeavraTaskFinding).check(Schema.isMaxLength(8)),
  candidateCause: Schema.NullOr(
    Schema.Struct({ kind: Schema.Literal("HYPOTHESIS"), text: text(1000) }),
  ),
  uncertainties: Schema.Array(text(250)).check(Schema.isMaxLength(8)),
  sourceReferences: Schema.Array(sourceReference).check(Schema.isMaxLength(8)),
  constraints: Schema.Array(text(250)).check(Schema.isMaxLength(8)),
})
  .check(
    Schema.makeFilter(
      (packet) =>
        utf8.encode(JSON.stringify(packet)).byteLength <= WEAVRA_ANALYSIS_CONTEXT_MAX_BYTES &&
        new Set(packet.sourceReferences.map((source) => source.path)).size ===
          packet.sourceReferences.length &&
        packet.observations.every(
          ({ reference }) =>
            reference.kind === "message" ||
            packet.sourceReferences.some((source) => source.path === reference.path),
        ),
    ),
  )
  .pipe(closed);
export type WeavraAnalysisContext = typeof WeavraAnalysisContext.Type;

