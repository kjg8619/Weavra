const sameBinding = Schema.toEquivalence(WeavraTaskBinding);
export const WeavraTaskExecution = Schema.Struct({
  binding: WeavraTaskBinding,
  previewId: identifier,
  previewDigest: digest,
  configDigest: digest,
  confirmedProjectRevision: counter,
  confirmCommandId: Schema.NullOr(CommandId),
  receipt: Schema.NullOr(WeavraTaskReceipt),
  // Optional only for legacy rows. New confirmation requires this presentation.
  preview: Schema.optionalKey(WeavraTaskPreview),
})
  .check(
    Schema.makeFilter(
      (execution) =>
        execution.preview === undefined ||
        (sameBinding(execution.preview.taskBinding, execution.binding) &&
          execution.preview.previewId === execution.previewId &&
          execution.preview.previewDigest === execution.previewDigest &&
          execution.preview.configDigest === execution.configDigest &&
          execution.preview.projectRevision === execution.confirmedProjectRevision),
    ),
    Schema.makeFilter(
      (execution) =>
        execution.receipt === null ||
        (execution.confirmCommandId !== null &&
          execution.receipt.executionId === execution.binding.executionId &&
          (execution.receipt.status === "UNKNOWN" ||
            (JSON.stringify(execution.receipt.admission.metadata.binding) ===
              JSON.stringify(execution.binding) &&
              execution.receipt.admission.metadata.previewDigest === execution.previewDigest &&
              execution.receipt.admission.metadata.configDigest === execution.configDigest &&
              execution.receipt.admission.metadata.confirmedProjectRevision ===
                execution.confirmedProjectRevision))),
    ),
  )
  .pipe(closed);
export type WeavraTaskExecution = typeof WeavraTaskExecution.Type;

export const WeavraTask = Schema.Struct({
  id: WeavraTaskId,
  createCommandId: Schema.optionalKey(CommandId),
  environmentId: EnvironmentId,
  projectId: ProjectId,
  threadId: ThreadId,
  // Retain the server's selected mapping separately from the realpath identity.
  target: Schema.Struct({
    workspaceRoot: absolutePath,
    worktreePath: Schema.NullOr(absolutePath),
  }),
  checkout: WeavraCheckoutIdentity,
  phase: WeavraTaskPhase,
  revision: positive,
  context: Schema.NullOr(WeavraAnalysisContext),
  execution: Schema.NullOr(WeavraTaskExecution),
  failureSummary: Schema.optionalKey(WeavraTaskFailureSummary),
  ownership: Schema.Struct({ generation: positive, state: WeavraTaskOwnershipState }),
  createdAt: IsoDateTime,
  updatedAt: IsoDateTime,
})
  .check(
    Schema.makeFilter((task) => {
      if (task.ownership.state === "released" && task.phase !== "finished") return false;
      if (
        task.context?.observations.some(
          (item) => item.reference.kind === "message" && item.reference.threadId !== task.threadId,
        )
      )
        return false;
      if (
        task.failureSummary !== undefined &&
        (task.execution?.receipt?.status !== "FOUND" ||
          task.execution.receipt.run === null ||
          task.execution.receipt.run.status === "COMPLETED" ||
          task.execution.receipt.admission.cleanup !== "CONFIRMED")
      )
        return false;
      const binding = task.execution?.binding;
      return (
        binding === undefined ||
        (binding.taskId === task.id &&
          binding.environmentId === task.environmentId &&
          binding.projectId === task.projectId &&
          binding.threadId === task.threadId &&
          JSON.stringify(binding.checkout) === JSON.stringify(task.checkout) &&
          binding.packetVersion === task.context?.packetVersion)
      );
    }),
  )
  .pipe(closed);
export type WeavraTask = typeof WeavraTask.Type;

